import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const root = process.cwd();
const dataDirectory = path.join(
  root,
  'apps/mobile/src/modules/curriculum/content/data',
);
const unitsDirectory = path.join(dataDirectory, 'units');
const outputPath = path.join(root, 'docs/CONTENT_STATS.md');
const collectionNames = ['topics', 'skills', 'concepts', 'lessons', 'pathNodes', 'exercises'];

const curriculum = JSON.parse(await readFile(path.join(dataDirectory, 'curriculum.json'), 'utf8'));
const unitFileNames = (await readdir(unitsDirectory))
  .filter((fileName) => fileName.endsWith('.json'))
  .sort();
const units = await Promise.all(
  unitFileNames.map(async (fileName) =>
    JSON.parse(await readFile(path.join(unitsDirectory, fileName), 'utf8')),
  ),
);
const unitsById = new Map(units.map((unit) => [unit.unitId, unit]));
const expectedUnitIds = curriculum.subjects.flatMap((subject) => subject.unitIds);
const unexpectedUnitIds = units
  .map((unit) => unit.unitId)
  .filter((unitId) => !expectedUnitIds.includes(unitId));
const missingUnitIds = expectedUnitIds.filter((unitId) => !unitsById.has(unitId));

if (unexpectedUnitIds.length > 0 || missingUnitIds.length > 0) {
  throw new Error(
    `Content unit index drifted. Missing: ${missingUnitIds.join(', ') || 'none'}; ` +
      `unexpected: ${unexpectedUnitIds.join(', ') || 'none'}.`,
  );
}

const summarize = (subjectUnits) => ({
  units: subjectUnits.length,
  ...Object.fromEntries(
    collectionNames.map((name) => [
      name,
      subjectUnits.reduce((total, unit) => total + unit[name].length, 0),
    ]),
  ),
  approvedLessons: subjectUnits
    .flatMap((unit) => unit.lessons)
    .filter((lesson) => lesson.provenance.reviewStatus === 'approved').length,
  approvedExercises: subjectUnits
    .flatMap((unit) => unit.exercises)
    .filter((exercise) => exercise.provenance.reviewStatus === 'approved').length,
});

const subjectRows = curriculum.subjects
  .filter((subject) => subject.unitIds.length > 0)
  .map((subject) => ({
    id: subject.id,
    title: subject.title,
    stats: summarize(subject.unitIds.map((unitId) => unitsById.get(unitId))),
  }));
const totals = summarize(units);
const columns = [
  ['units', 'Units'],
  ['topics', 'Topics'],
  ['skills', 'Skills'],
  ['concepts', 'Concepts'],
  ['lessons', 'Lessons'],
  ['pathNodes', 'Path nodes'],
  ['exercises', 'Exercises'],
  ['approvedLessons', 'Approved lessons'],
  ['approvedExercises', 'Approved exercises'],
];
const row = (label, stats) =>
  `| ${label} | ${columns.map(([key]) => stats[key]).join(' | ')} |`;
const document = `${[
  '# Content statistics',
  '',
  '<!-- Generated by npm run content:stats:update. Do not edit by hand. -->',
  '',
  `Content version: \`${curriculum.contentVersion}\`  `,
  `Curriculum version: \`${curriculum.curriculumVersion}\``,
  '',
  `| Subject | ${columns.map(([, label]) => label).join(' | ')} |`,
  `| --- | ${columns.map(() => '---:').join(' | ')} |`,
  ...subjectRows.map(({ id, title, stats }) => row(`${title} (\`${id}\`)`, stats)),
  row('Total', totals),
  '',
  'Only records with a valid human subject-matter approval may enter the production bundle.',
  '',
].join('\n')}\n`;

if (process.argv.includes('--write')) {
  await writeFile(outputPath, document);
  console.log(`Updated ${path.relative(root, outputPath)}.`);
} else {
  let current;
  try {
    current = await readFile(outputPath, 'utf8');
  } catch {
    current = '';
  }
  if (current !== document) {
    console.error('Content statistics are stale. Run `npm run content:stats:update` and commit the result.');
    process.exitCode = 1;
  } else {
    console.log(`Content statistics match ${unitFileNames.length} authored unit files.`);
  }
}
